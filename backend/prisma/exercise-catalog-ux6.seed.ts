import type { ExerciseSeed } from './exercise-catalog.seed';

// Additive editorial variants. Instructions describe a proposed recording convention,
// never attest how an existing historical set was actually recorded.
function variant(
  catalogKey: string,
  name: string,
  primaryMuscleGroupKey: string,
  movementPattern: ExerciseSeed['movementPattern'],
  movementType: ExerciseSeed['movementType'],
  equipmentType: ExerciseSeed['equipmentType'],
  resistanceType: ExerciseSeed['resistanceType'],
  instructions: string,
  extra: Partial<ExerciseSeed> = {},
): ExerciseSeed {
  return {
    catalogKey,
    name,
    primaryMuscleGroupKey,
    movementPattern,
    movementType,
    equipmentType,
    resistanceType,
    equipment: name,
    secondaryMuscleGroupKeys: [],
    machineType: null,
    grip: null,
    gripWidth: null,
    bodyPosition: 'SEATED',
    laterality: 'BILATERAL',
    movementPlane: 'SAGITTAL',
    difficulty: 'BEGINNER',
    oneRmSuitability: 'NOT_SUITABLE',
    description:
      'Variante editorial independiente. Comprueba el ajuste y un recorrido cómodo antes de registrar tu carga.',
    instructions,
    ...extra,
  };
}
